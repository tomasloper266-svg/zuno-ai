import type { ChatErrorKind } from '../lib/engine'

export type Lang = 'en' | 'ar'

/** Title + body pair for one chat error banner. */
export interface BannerCopy {
  title: string
  body: string
}

export interface EntryItem {
  id: 'coding' | 'learning' | 'writing' | 'explore'
  title: string
  desc: string
  prompt: string
}

export interface Strings {
  tagline: string
  headline: string
  headlineAccentWord: string
  sub: string
  inputPlaceholder: string
  send: string
  footerNote: string
  footerNoteLive: string
  version: string
  /** Gentle one-time banner when a conversation write fails (quota / private mode). */
  storageNotice: string
  /** Local-only storage disclosure: conversations do not sync across devices. */
  storageLocalNote: string
  entries: EntryItem[]
  nav: { theme: string; language: string; home: string }
  chat: {
    newChat: string
    history: string
    historyEmpty: string
    searchPlaceholder: string
    /** Empty state: conversations exist but none match the search query. */
    searchNoResults: string
    placeholder: string
    hint: string
    demoBadge: string
    demoNote: string
    liveBadge: string
    liveNote: string
    privacyNote: string
    /** Shown in live mode when only the newest messages of a long conversation were sent. */
    contextTrimmed: string
    emptyTitle: string
    emptyHint: string
    /** Seeded as the first message of every new conversation. */
    greeting: string
    copy: string
    copied: string
    /** Header kebab menu holding conversation-level actions (copy, export). */
    conversationActions: string
    copyConversation: string
    exportMarkdown: string
    exportJson: string
    regenerate: string
    retry: string
    /** Stop button shown while a reply is streaming in. */
    stopGenerating: string
    /** Badge on a reply cut short by the stop button or the stall watchdog. */
    stopped: string
    /** Badge on a reply whose stream failed midway — its partial text was salvaged. */
    failed: string
    /** Composer limit gauge, shown at ≥90% of the message/request limits. */
    limitCounter: string
    /** Composer error shown when the draft or request total exceeds its limit. */
    limitExceeded: string
    errors: Record<ChatErrorKind, BannerCopy>
    /** Shown instead of errors.connection when the browser reports being offline. */
    offline: BannerCopy
    /** Delete confirmation dialog — a destructive action is never one click. */
    cancel: string
    deleteConfirmTitle: string
    deleteConfirmBody: string
    deleteConfirmAction: string
    /** Inline rename (from the actions menu): the menu item and the editor's aria-label. */
    rename: string
    renameLabel: string
    delete: string
    you: string
    jumpToLatest: string
    messagesRegion: string
  }
}

